import assert from 'node:assert/strict';
import {closeContext,tradingDate,chooseCompletedBar} from './us-close-calendar.mjs';
const expected=t=>closeContext(new Date(t)).expected;
assert.equal(expected('2026-11-26T22:00:00Z'),'20261125');
assert.equal(expected('2026-11-27T17:59:00Z'),'20261125');
assert.equal(expected('2026-11-27T18:29:00Z'),'20261125');
assert.equal(expected('2026-11-27T18:30:00Z'),'20261127');
assert.equal(expected('2026-11-28T08:00:00Z'),'20261127');
assert.equal(expected('2026-11-30T21:29:00Z'),'20261127');
assert.equal(expected('2026-11-30T21:30:00Z'),'20261130');
assert.equal(expected('2026-07-06T20:30:00Z'),'20260706');
assert.equal(expected('2029-01-03T22:00:00Z'),null);
assert.equal(tradingDate('20261126'),false);
assert.equal(tradingDate('20261131'),false);
assert.equal(tradingDate('20261128'),false);
assert.equal(tradingDate('20261127'),true);
const bar=date=>({ok:true,date,close:10});
let calls=0;
const newest=await chooseCompletedBar('20261127',[['primary',async()=>bar('20261125')],['fallback',async()=>{calls++;return bar('20261127')}]]);
assert.equal(newest.date,'20261127');assert.equal(newest.closeStatus,'current');assert.equal(calls,1);
const current=await chooseCompletedBar('20261127',[['primary',async()=>bar('20261127')],['fallback',async()=>{calls++;throw Error('unexpected')}]]);
assert.equal(current.closeStatus,'current');assert.equal(calls,1);
const stale=await chooseCompletedBar('20261127',[['primary',async()=>bar('20261124')],['fallback',async()=>bar('20261125')]]);
assert.equal(stale.date,'20261125');assert.equal(stale.closeStatus,'stale');assert.equal(stale.expectedDate,'20261127');
const wrong=await chooseCompletedBar('20261127',[['holiday',async()=>bar('20261126')],['future',async()=>bar('20261130')]]);
assert.equal(wrong.ok,false);assert.equal(wrong.closeStatus,'unavailable');
await assert.rejects(chooseCompletedBar(null,[]));
console.log('PASS: US completed session, holiday, early close, DST, delayed and stale fallback checks');
