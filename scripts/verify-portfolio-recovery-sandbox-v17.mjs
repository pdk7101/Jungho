import assert from 'node:assert/strict';
import {webcrypto} from 'node:crypto';
import {LEGACY_KEYS,createBackup} from '../portfolio-recovery-v17.mjs';
import {SANDBOX_KEY,sandboxStore,initializeSandbox,restoreSandbox,rollbackSandbox} from '../portfolio-recovery-sandbox-v17.mjs';
const data=Object.fromEntries(LEGACY_KEYS.map(k=>[k,null]));
data[LEGACY_KEYS[0]]='{"reit":{"qty":33,"avg":3944}}';
const modified={...data,[LEGACY_KEYS[0]]:'{"reit":{"qty":40,"avg":3900}}',[LEGACY_KEYS[5]]:'{"cony":50000}'};
const map=new Map(Object.entries(data));let failWrite=false;
const storage={getItem:k=>map.get(k)??null,setItem(k,v){assert.equal(k,SANDBOX_KEY);if(failWrite)throw Error('quota');map.set(k,v)}};
let tail=Promise.resolve();
const locks={request(name,options,fn){assert.equal(name,SANDBOX_KEY);const next=tail.then(fn);tail=next.catch(()=>{});return next}};
assert.throws(()=>sandboxStore(storage,null));
const store=sandboxStore(storage,locks),opts={cryptoImpl:webcrypto};
const before=await initializeSandbox(store,data,opts);assert.equal(before.revision,1);
await assert.rejects(initializeSandbox(store,data,opts));
const backup=await createBackup(modified,opts);
const args={...opts,expectedRevision:1,expectedCurrent:data,confirm:true};
await assert.rejects(restoreSandbox(store,backup,{...args,confirm:false}));
await assert.rejects(rollbackSandbox(store,{...opts,expectedRevision:1,confirm:true}));
const original=map.get(SANDBOX_KEY);
failWrite=true;await assert.rejects(restoreSandbox(store,backup,args));assert.equal(map.get(SANDBOX_KEY),original);failWrite=false;
const results=await Promise.allSettled([restoreSandbox(store,backup,args),restoreSandbox(store,backup,args)]);
assert.equal(results.filter(x=>x.status==='fulfilled').length,1);assert.equal(results.filter(x=>x.status==='rejected').length,1);
const applied=JSON.parse(map.get(SANDBOX_KEY));assert.equal(applied.revision,2);assert.deepEqual(applied.current.records,modified);assert.deepEqual(applied.previous.records,data);
await assert.rejects(rollbackSandbox(store,{...opts,expectedRevision:1,confirm:true}));
failWrite=true;await assert.rejects(rollbackSandbox(store,{...opts,expectedRevision:2,confirm:true}));assert.deepEqual(JSON.parse(map.get(SANDBOX_KEY)),applied);failWrite=false;
const rolled=await rollbackSandbox(store,{...opts,expectedRevision:2,confirm:true});
assert.equal(rolled.revision,3);assert.deepEqual(rolled.current.records,data);assert.deepEqual(rolled.previous.records,modified);
for(const k of LEGACY_KEYS)assert.equal(map.get(k),data[k]);
console.log('PASS: exclusive lock, stale revision, confirmed restore, quota failure, rollback, untouched legacy records');
