import assert from 'node:assert/strict';
import fs from 'node:fs';
import {webcrypto} from 'node:crypto';
import {LEGACY_KEYS,canonicalRecords,readRecords,createBackup,verifyBackup,compareRecords,stageRecovery,planSync} from '../portfolio-recovery-v17.mjs';
const legacy=fs.readFileSync(new URL('../portfolio-sync.js',import.meta.url),'utf8');
const keys=JSON.parse(legacy.match(/const KEYS=(\[[^\n]+\]);/)[1].replaceAll("'",'"'));
assert.deepEqual(LEGACY_KEYS,keys);
const empty=Object.fromEntries(keys.map(k=>[k,null]));
const a=keys[0],b=keys[5],c=keys[11],d=keys[10];
const data={...empty,[a]:'{"reit":{"qty":33,"avg":3944}}',[b]:'{"cony":37073}',[c]:'{"robot":{"max":9500}}',[d]:'{"mode":"manual"}'};
const storage=new Map([...Object.entries(data),['isa-portfolio-sync-config-v1','synthetic secret'],['unrelated','other']]);
assert.deepEqual(readRecords(storageAdapter(storage)),data);
function storageAdapter(m){return {getItem:k=>m.get(k)??null}}
assert.throws(()=>canonicalRecords({...data,unknown:'{}'}));
assert.throws(()=>canonicalRecords({...data,[a]:'null'}));
assert.throws(()=>canonicalRecords({...data,[a]:'bad'}));
const missing={...data};delete missing[a];assert.throws(()=>canonicalRecords(missing));
const opts={cryptoImpl:webcrypto,createdAt:'2026-11-27T00:00:00Z',revision:8};
const backup=await createBackup(data,opts);
assert.deepEqual(await verifyBackup(JSON.parse(JSON.stringify(backup)),opts),backup);
assert.equal(backup.sha256.length,64);
assert.ok(!JSON.stringify(backup).includes('synthetic secret'));
await assert.rejects(verifyBackup({...backup,records:{...data,[b]:'{"cony":0}'}},opts));
await assert.rejects(verifyBackup({...backup,revision:9},opts));
await assert.rejects(verifyBackup({...backup,extra:'bad'},opts));
const local={...data,[a]:'{"reit":{"qty":34,"avg":3944}}'};
const recovery=await stageRecovery({current:local,expectedCurrent:local,backup,cryptoImpl:webcrypto});
assert.equal(recovery.liveApplied,false);
assert.deepEqual(recovery.before.records,local);
assert.deepEqual(recovery.target.records,data);
assert.equal(recovery.changes.find(x=>x.key===a).status,'would_replace');
assert.equal(compareRecords(data,empty).find(x=>x.key===b).status,'would_remove');
assert.equal(compareRecords(empty,data).find(x=>x.key===b).status,'would_add');
await assert.rejects(stageRecovery({current:local,expectedCurrent:data,backup,cryptoImpl:webcrypto}));
assert.equal(storage.get(a),data[a]);
const base={revision:8,data};
assert.equal(planSync({base:null,local,remote:{revision:0,data:null}}).status,'initial_confirmation');
assert.equal(planSync({base:null,local,remote:base}).status,'initial_conflict');
assert.equal(planSync({base:null,local:data,remote:base}).status,'identical');
assert.equal(planSync({base,local,remote:{revision:7,data}}).status,'remote_reset_or_diverged');
assert.equal(planSync({base,local,remote:{revision:8,data:local}}).status,'remote_reset_or_diverged');
assert.equal(planSync({base,local,remote:{revision:0,data:null}}).data,null);
const remote={revision:9,data:{...data,[b]:'{"cony":42000}'}};
const merged=planSync({base,local,remote});
assert.equal(merged.status,'ready');assert.equal(merged.data[a],local[a]);assert.equal(merged.data[b],remote.data[b]);assert.equal(merged.data[c],data[c]);
assert.equal(planSync({base,local:data,remote}).status,'read_only');
const conflict=planSync({base,local,remote:{revision:9,data:{...data,[a]:'{"reit":{"qty":35}}'}}});
assert.equal(conflict.status,'conflict');assert.deepEqual(conflict.conflicts,[a]);assert.equal(conflict.data,null);
assert.throws(()=>planSync({base,local,remote:{revision:9,data:{...data,watchlist:'{}'}}}));
console.log('PASS: exact v1 contract, backup integrity, staged recovery, revision and conflict protection');
