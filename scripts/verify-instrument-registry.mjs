import assert from 'node:assert/strict';
import {instrument,addInstrument,addHolding,archiveHolding,planQuotes,totals} from '../instrument-registry.mjs';
let state={catalog:{},holdings:{}};
const fund={market:'KR',venue:'KRX-ETF',symbol:'0167B0',name:'Synthetic ETF'};
const i=instrument(fund);
state=addHolding(state,'kiwoom-isa',fund);
state=addHolding(state,'toss-kr',fund);
assert.equal(Object.keys(state.catalog).length,1);
assert.equal(Object.keys(state.holdings).length,2);
assert.deepEqual(addHolding(state,'toss-kr',fund),state);
assert.throws(()=>addHolding(state,'toss-us',fund),/mismatch/);
assert.throws(()=>instrument({...fund,symbol:'../bad'}),/identity/);
assert.throws(()=>archiveHolding(state,'toss-kr|'+i.id),/not confirmed/);
let h=state.holdings['toss-kr|'+i.id];h.qty=0;
const archived=archiveHolding(state,h.id);
assert.equal(archived.holdings[h.id].archived,true);
assert.equal(h.archived,false);
assert.equal(totals(state,{}).complete,false);
const isa=state.holdings['kiwoom-isa|'+i.id];isa.qty=2;isa.avgKRW=1000;
assert.deepEqual(totals(state,{[i.id]:{amountKRW:900,date:'2026-11-26'}}),{costKnown:2000,valueKnown:1800,complete:true,missing:[]});
for(let n=0;n<98;n++)state=addHolding(state,'kiwoom-isa',{...fund,symbol:String(100000+n)});
const us={market:'US',venue:'US',symbol:'TEST',name:'Synthetic US'};
state=addHolding(state,'toss-us',us);
assert.equal(Object.keys(state.catalog).length,100);
assert.throws(()=>addInstrument(state.catalog,{...us,symbol:'TEST2'}),/limit/);
const p=planQuotes(state.catalog,state.holdings,'2026-11-26',0);
assert.equal(p.kr.length,1);
assert.equal(p.kr[0].ids.length,99);
assert.equal(p.kr[0].requestUnits,1);
assert.equal(p.us.length,0);
assert.equal(p.deferred.length,1);
assert.equal(planQuotes(state.catalog,state.holdings,'2026-11-26',1).us.length,1);
assert.equal(totals(state,{}).complete,false);
console.log('PASS: synthetic 100-instrument catalog, account separation, deduplication, archive guard, missing prices and budget planner');
