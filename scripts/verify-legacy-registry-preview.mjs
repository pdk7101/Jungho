import assert from 'node:assert/strict';
import {aliases,projectLegacy,compareBasis,quoteRegistry,registerForReview} from '../legacy-registry-preview.mjs';
import {planQuotes} from '../instrument-registry.mjs';
const isaRows={},tossRows=[];
for(const a of aliases){
 if(a.account==='kiwoom-isa')isaRows[a.legacyId]={qty:2,avg:1000};
 else tossRows.push({market:a.account==='toss-us'?'us':'domestic',id:a.legacyId,qty:3,avg:2000,official:false});
}
const before=JSON.stringify({isaRows,tossRows});
const p=projectLegacy({isaRows,tossRows,shared:true});
assert.equal(JSON.stringify({isaRows,tossRows}),before);
assert.equal(Object.keys(p.state.catalog).length,15);
assert.equal(Object.keys(p.state.holdings).length,20);
assert.equal(p.diagnostics.length,0);
assert.equal(p.migrationReady,false);
assert.equal(p.state.holdings['kiwoom-isa|KR:KRX-ETF:329200'].qty,2);
assert.equal(p.state.holdings['toss-kr|KR:KRX-ETF:329200'].qty,3);
const checks=compareBasis(p,{'kiwoom-isa':12000,'toss-kr':54000,'toss-us':30000});
assert.equal(Object.values(checks).every(x=>x.match),true);
const add=registerForReview(p.state,'toss-us',{market:'US',venue:'US',symbol:'QQQM',name:'QQQM'});
assert.equal(add.signal,'wait');
assert.equal(add.state.holdings[add.id].qty,null);
assert.equal(add.state.holdings[add.id].avgKRW,null);
const addKR=registerForReview(add.state,'toss-kr',{market:'KR',venue:'KRX-ETF',symbol:'ABC123',name:'Synthetic ETF'});
const req=planQuotes(addKR.state.catalog,addKR.state.holdings,'2026-11-27',10);
assert.equal(req.kr.length,3);
assert.equal(req.us.length,6);
assert.equal(req.kr.find(x=>x.venue==='KRX-ETF').ids.length,9);
const projected=quoteRegistry(addKR.state);
assert.equal(Object.keys(projected.catalog).length,6);
assert.equal(Object.keys(projected.holdings).length,6);
assert.equal(JSON.stringify(projected).includes('avgKRW'),false);
assert.equal(JSON.stringify(projected).includes('qty'),false);
assert.equal(JSON.stringify(projected).includes('kiwoom-isa'),false);
const lost=projectLegacy({isaRows:{...isaRows,sol:{qty:'',avg:1000}},tossRows:tossRows.map(r=>r.id==='schd'?{...r,official:true}:r)});
assert.equal(lost.diagnostics.length,2);
assert.equal(lost.state.holdings['toss-us|US:US:SCHD'].qty,null);
assert.equal(lost.state.holdings['kiwoom-isa|KR:KRX-ETF:0167B0'].qty,null);
assert.equal(compareBasis(lost,{'kiwoom-isa':12000})['kiwoom-isa'].match,false);
console.log('PASS: legacy 20 positions / 15 unique symbols, read-only migration, separate accounts, dynamic quote projection, unknown basis preserved');
