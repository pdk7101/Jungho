import assert from 'node:assert/strict';
import {initialPreview,previewAdd,previewRows,previewCounts} from '../registry-ui-preview.mjs';
const start=initialPreview();
assert.deepEqual(previewCounts(start),{instruments:15,positions:20,krRequests:3,usSymbols:5});
const input={account:'toss-us',symbol:' qqqm ',name:'QQQM'};
const a=previewAdd(start,input);
assert.equal(a.duplicate,false);
assert.equal(previewCounts(a.model).usSymbols,6);
assert.equal(previewCounts(start).usSymbols,5);
const row=previewRows(a.model,'toss-us').find(r=>r.symbol==='QQQM');
assert.equal(row.qty,null);assert.equal(row.avgKRW,null);assert.equal(row.status,'보류');
assert.equal(previewAdd(a.model,input).duplicate,true);
const sol=previewAdd(a.model,{account:'toss-kr',venue:'KRX-ETF',symbol:'0167B0',name:'SOL 200타겟위클리커버드콜'});
assert.equal(previewCounts(sol.model).instruments,16);
assert.equal(previewCounts(sol.model).positions,22);
assert.equal(previewCounts(sol.model).krRequests,3);
assert.equal(previewRows(sol.model,'kiwoom-isa').find(r=>r.symbol==='0167B0').added,false);
assert.equal(previewRows(sol.model,'toss-kr').find(r=>r.symbol==='0167B0').added,true);
assert.throws(()=>previewAdd(start,{account:'kiwoom-isa',venue:'KOSPI',symbol:'QQQM',name:'bad'}));
assert.throws(()=>previewAdd(start,{account:'unknown',symbol:'QQQM',name:'bad'}));
assert.throws(()=>previewAdd(start,{account:'toss-us',symbol:'abc!',name:'bad'}));
let current=start;
for(let i=0;i<85;i++)current=previewAdd(current,{account:'toss-us',symbol:'TEST'+i,name:'Synthetic '+i}).model;
assert.equal(previewCounts(current).instruments,100);
assert.throws(()=>previewAdd(current,{account:'toss-us',symbol:'EXTRA',name:'Synthetic extra'}));
console.log('PASS: preview account isolation, deduplication, unknown balances, symbol format and 100 instrument cap');
